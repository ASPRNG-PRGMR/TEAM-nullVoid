#!/usr/bin/env bash
# acli.sh - build/flash this firmware with arduino-cli instead of PlatformIO.
#
# PlatformIO is the documented path, but it is a big dependency and plenty of
# machines only have arduino-cli. This script does the same job: it flattens
# the src/ + include/ tree into a throwaway sketch (arduino-cli wants one
# directory) and compiles it with the board options that match platformio.ini.
#
#   ./tools/acli.sh build  uart          # compile the UART-link firmware
#   ./tools/acli.sh flash  uart          # compile + upload
#   ./tools/acli.sh flash  probe         # camera pin-map prober
#   ./tools/acli.sh flash  wifi          # Wi-Fi link
#   ./tools/acli.sh monitor              # 921600 console
#
# Env overrides: PORT (default /dev/ttyACM0), BUILD (default under /tmp).
set -euo pipefail

FW="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PORT="${PORT:-/dev/ttyACM0}"
BUILD="${BUILD:-/tmp/bb-acli}"
BAUD=921600

# Matches [common] in platformio.ini: 16 MB QIO flash, 8 MB OPI PSRAM, and
# CDC-on-boot off so Serial is UART0 behind the CH343 bridge.
FQBN='esp32:esp32:esp32s3'
FQBN+=':USBMode=hwcdc,CDCOnBoot=default'
FQBN+=',FlashMode=qio,FlashSize=16M'
FQBN+=',PartitionScheme=app3M_fat9M_16MB'
FQBN+=',DebugLevel=info,PSRAM=opi,LoopCore=1'

case "${2:-uart}" in
  wifi)  FLAGS='-DBB_BOARD_PROFILE=1 -DBB_LINK_DEFAULT=BB_LINK_WIFI' ;;
  uart)  FLAGS='-DBB_BOARD_PROFILE=1 -DBB_LINK_DEFAULT=BB_LINK_UART' ;;
  probe) FLAGS='-DBB_BOARD_PROFILE=1 -DBB_LINK_DEFAULT=BB_LINK_UART -DBB_RUN_PIN_PROBE=1' ;;
  *) echo "unknown target '${2}' (wifi|uart|probe)" >&2; exit 2 ;;
esac
TARGET="${2:-uart}"
SK="$BUILD/$TARGET"

assemble() {
  rm -rf "$SK"; mkdir -p "$SK"
  cp "$FW"/src/*.cpp "$SK"/
  cp "$FW"/include/*.h "$SK"/
  # secrets.h is gitignored and optional; link_wifi.cpp guards on __has_include.
  [ -f "$FW/include/secrets.h" ] && cp "$FW/include/secrets.h" "$SK"/
  echo '// generated by tools/acli.sh - setup()/loop() live in main.cpp' \
    > "$SK/$TARGET.ino"
}

compile() {
  assemble
  arduino-cli compile --fqbn "$FQBN" \
    --build-property "compiler.cpp.extra_flags=-std=gnu++17 -DBOARD_HAS_PSRAM $FLAGS" \
    --build-path "$BUILD/${TARGET}_out" "$SK"
}

case "${1:-build}" in
  build) compile ;;
  flash)
    compile
    arduino-cli upload -p "$PORT" --fqbn "$FQBN" \
      --input-dir "$BUILD/${TARGET}_out" "$SK"
    ;;
  monitor)
    arduino-cli monitor -p "$PORT" --config "baudrate=$BAUD"
    ;;
  *) echo "usage: $0 {build|flash|monitor} [wifi|uart|probe]" >&2; exit 2 ;;
esac
